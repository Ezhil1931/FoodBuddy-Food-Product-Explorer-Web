function mk(o) {
  const brands = o.brand ? (o.brands && o.brands.length ? o.brands : [o.brand]) : []
  const categoryTags = o.categoryTags || []
  const primaryCategory =
    categoryTags.find((t) => t.startsWith('en:')) || categoryTags[0] || null
  const image = o.image || null
  return {
    id: o.id || o.code,
    code: o.id || o.code,
    name: o.name || 'Unknown product',
    brand: brands[0] || 'Unknown brand',
    brands,
    quantity: o.quantity || '',
    image,
    images:
      o.images && o.images.length
        ? o.images
        : image
          ? [{ src: image, label: 'Front' }]
          : [],
    categories: [],
    categoryTags,
    primaryCategory,
    nutriscore: o.nutriscore || null,
    novaGroup: o.novaGroup ?? null,
    labelsTags: o.labelsTags || [],
    ingredientsText: o.ingredientsText || '',
    nutriments: o.nutriments || {},
    nutrientLevels: o.nutrientLevels || {},
    genericName: o.genericName || '',
    servingSize: o.servingSize || '',
    servingQuantity: o.servingQuantity || null,
    packaging: o.packaging || '',
    labels: o.labels || [],
    countries: o.countries || [],
    countriesTags: [],
    origins: o.origins || [],
    originsTags: [],
    manufacturingPlaces: o.manufacturingPlaces || [],
    manufacturingPlacesTags: [],
    stores: o.stores || [],
    purchasePlaces: [],
    ingredientsList: o.ingredientsList || [],
    allergens: o.allergens || [],
    allergensTags: [],
    tracesTags: o.tracesTags || [],
    additives: o.additives || [],
    additivesTags: o.additivesTags || [],
    ecoscore: o.ecoscore || null,
    embCodes: [],
    owner: o.owner || 'FoodBuddy catalog',
    uniqueScans: o.uniqueScans || 0,
    createdT: o.createdT || 1700000000,
    lastModifiedT: o.lastModifiedT || 1700000000,
  }
}

